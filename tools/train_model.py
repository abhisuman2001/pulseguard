#!/usr/bin/env python3
"""
Train the PulseGuard breath classifier (multinomial logistic regression)
on features produced by tools/simgen, and emit core/pg_model_weights.h.

Pure standard library on purpose: anyone can reproduce the model.

    python3 tools/train_model.py train.csv test.csv core/pg_model_weights.h
"""
import csv
import math
import random
import sys

CLASSES = ["normal", "leak", "occlusion", "stiff_lung", "disconnect"]
NFEAT = 6


def clamp(x, lo, hi):
    return lo if x < lo else hi if x > hi else x


def features(row):
    # MUST mirror pg_features_vector() in core/pg_core.c
    R, C, leak, qpk, pm, vt = (float(row[k]) for k in
                               ("R", "C", "leak_frac", "qpeak", "paw_mean", "vt"))
    return [
        math.log(clamp(R, 0.5, 200.0)),
        math.log(clamp(C, 1.0, 200.0)),
        clamp(leak, -1.0, 1.0),
        clamp(qpk, 0.0, 5.0),
        clamp(pm, 0.0, 50.0) / 10.0,
        clamp(vt, 0.0, 3000.0) / 500.0,
    ]


def load(path):
    X, y = [], []
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            X.append(features(row))
            y.append(int(row["label"]))
    return X, y


def softmax(z):
    m = max(z)
    e = [math.exp(v - m) for v in z]
    s = sum(e)
    return [v / s for v in e]


def predict(W, b, x):
    return softmax([b[c] + sum(W[c][i] * x[i] for i in range(NFEAT))
                    for c in range(len(CLASSES))])


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(2)
    Xtr, ytr = load(sys.argv[1])
    Xte, yte = load(sys.argv[2])

    mean = [sum(x[i] for x in Xtr) / len(Xtr) for i in range(NFEAT)]
    std = [math.sqrt(sum((x[i] - mean[i]) ** 2 for x in Xtr) / len(Xtr)) or 1.0
           for i in range(NFEAT)]
    norm = lambda X: [[(x[i] - mean[i]) / std[i] for i in range(NFEAT)] for x in X]
    Ntr, Nte = norm(Xtr), norm(Xte)

    K = len(CLASSES)
    W = [[0.0] * NFEAT for _ in range(K)]
    b = [0.0] * K
    lr, l2 = 0.5, 1e-3
    idx = list(range(len(Ntr)))
    random.seed(7)
    for epoch in range(300):
        random.shuffle(idx)
        gW = [[0.0] * NFEAT for _ in range(K)]
        gb = [0.0] * K
        loss = 0.0
        for j in idx:
            x, t = Ntr[j], ytr[j]
            p = predict(W, b, x)
            loss -= math.log(max(p[t], 1e-12))
            for c in range(K):
                d = p[c] - (1.0 if c == t else 0.0)
                gb[c] += d
                for i in range(NFEAT):
                    gW[c][i] += d * x[i]
        n = len(Ntr)
        for c in range(K):
            b[c] -= lr * gb[c] / n
            for i in range(NFEAT):
                W[c][i] -= lr * (gW[c][i] / n + l2 * W[c][i])
        if epoch % 50 == 0:
            print(f"epoch {epoch:3d} loss {loss / n:.4f}", file=sys.stderr)

    # evaluation
    conf = [[0] * K for _ in range(K)]
    for x, t in zip(Nte, yte):
        p = predict(W, b, x)
        conf[t][max(range(K), key=lambda c: p[c])] += 1
    acc = sum(conf[i][i] for i in range(K)) / len(yte)
    print(f"held-out accuracy: {acc * 100:.1f}%  (n={len(yte)})", file=sys.stderr)
    print("confusion (rows=true):", file=sys.stderr)
    for i in range(K):
        print(f"  {CLASSES[i]:>11s} {conf[i]}", file=sys.stderr)

    f = lambda v: f"{v:.6f}f"
    with open(sys.argv[3], "w") as out:
        out.write("/* AUTO-GENERATED by tools/train_model.py - do not edit.\n")
        out.write(f" * Multinomial logistic regression, {NFEAT} features, {K} classes.\n")
        out.write(f" * Trained on {len(ytr)} simulated breaths; held-out accuracy {acc * 100:.1f}%.\n */\n")
        out.write("#ifndef PG_MODEL_WEIGHTS_H\n#define PG_MODEL_WEIGHTS_H\n")
        out.write(f"#define PG_MODEL_ACCURACY {acc:.4f}f\n")
        out.write(f"static const float PG_MODEL_MEAN[{NFEAT}] = {{{', '.join(map(f, mean))}}};\n")
        out.write(f"static const float PG_MODEL_STD[{NFEAT}]  = {{{', '.join(map(f, std))}}};\n")
        out.write(f"static const float PG_MODEL_W[{K}][{NFEAT}] = {{\n")
        for c in range(K):
            out.write(f"    {{{', '.join(map(f, W[c]))}}}, /* {CLASSES[c]} */\n")
        out.write("};\n")
        out.write(f"static const float PG_MODEL_B[{K}] = {{{', '.join(map(f, b))}}};\n")
        out.write("#endif\n")


if __name__ == "__main__":
    main()
